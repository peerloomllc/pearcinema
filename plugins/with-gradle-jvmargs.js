// Expo config plugin: the Gradle daemon's JVM arguments.
//
// Gradle runs a SEPARATE daemon for every distinct org.gradle.jvmargs, and each one
// holds 2-4 GB. The PeerLoom apps share one Gradle version (8.14.3), so if they also
// share these exact arguments, building any of them reuses one daemon instead of
// forking another. The value is the suite-wide one decided on 2026-07-30 (company
// TODO, "Normalize org.gradle.jvmargs"): the same string in every app, verbatim.
//
// The G1 flags are the part that fixes the symptom that started this, a daemon
// holding 3.6 GB at zero CPU between builds: MinHeapFreeRatio/MaxHeapFreeRatio let
// it hand unused heap back to the OS.
//
// A plugin rather than a gradle.properties edit because android/ is gitignored and
// regenerated by `expo prebuild`. Same shape as with-android-abis.
//
// CHANGE IT IN EVERY APP OR NOT AT ALL. One app with different arguments is one more
// daemon, which is exactly the waste this removes.

const { withGradleProperties } = require('expo/config-plugins')

const JVMARGS = '-Xmx2048m -XX:MaxMetaspaceSize=512m -XX:+UseG1GC -XX:MinHeapFreeRatio=10 -XX:MaxHeapFreeRatio=30'

module.exports = function withGradleJvmargs (config) {
  return withGradleProperties(config, (cfg) => {
    const props = cfg.modResults
    const key = 'org.gradle.jvmargs'
    const existing = props.find((p) => p.type === 'property' && p.key === key)
    if (existing) existing.value = JVMARGS
    else props.push({ type: 'property', key, value: JVMARGS })
    return cfg
  })
}
