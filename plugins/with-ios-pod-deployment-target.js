// Expo config plugin: raise every CocoaPods target to the app's iOS deployment
// target.
//
// Xcode 27 (installed on the Mac mini 2026-09-14) only accepts deployment targets
// from 15.0 up. A pod whose podspec still says less fails the whole archive:
//   Pods.xcodeproj: error: The iOS deployment target 'IPHONEOS_DEPLOYMENT_TARGET'
//   is set to 13.4, but the range of supported deployment target versions is 15.0
//   to 27.0.x. (in target 'RNCAsyncStorage-RNCAsyncStorage_resources' ...)
// @react-native-async-storage/async-storage declares ios 13.4. The app itself
// already targets 15.1, so lifting a pod to that changes nothing it can run on.
//
// ios/ is regenerated by `expo prebuild`, so the Podfile edit has to live here.
// It is appended inside post_install, after react_native_post_install, so nothing
// later in that hook sets the old value back.

const fs = require('fs')
const path = require('path')
const { withDangerousMod } = require('expo/config-plugins')

const MARKER = '# with-ios-pod-deployment-target'
const MIN = '15.1'

const SNIPPET = `
    ${MARKER}
    installer.pods_project.targets.each do |target|
      target.build_configurations.each do |bc|
        current = bc.build_settings['IPHONEOS_DEPLOYMENT_TARGET']
        if current.nil? || Gem::Version.new(current) < Gem::Version.new('${MIN}')
          bc.build_settings['IPHONEOS_DEPLOYMENT_TARGET'] = '${MIN}'
        end
      end
    end
`

module.exports = function withIosPodDeploymentTarget (config) {
  return withDangerousMod(config, ['ios', (cfg) => {
    const file = path.join(cfg.modRequest.platformProjectRoot, 'Podfile')
    let src = fs.readFileSync(file, 'utf8')
    if (src.includes(MARKER)) return cfg
    // The end of the react_native_post_install(...) call inside post_install.
    const re = /(post_install do \|installer\|\n\s*react_native_post_install\([\s\S]*?\n\s*\)\n)/
    if (!re.test(src)) throw new Error('with-ios-pod-deployment-target: post_install block not found in Podfile')
    src = src.replace(re, `$1${SNIPPET}`)
    fs.writeFileSync(file, src)
    return cfg
  }])
}
